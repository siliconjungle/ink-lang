import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const directory=path.resolve(process.argv[2]);
globalThis.fetch=async url=>new Response(await fs.readFile(new URL(url)));
const base=pathToFileURL(directory+'/');
const {runBenchmark}=await import(new URL('runner.mjs',base));
const validateOnly=process.argv[3]==='--validate';
const result=await runBenchmark(base,{validateOnly,progress:message=>console.log(message)});
await fs.writeFile(path.join(directory,validateOnly?'node-validation.json':'node-results.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({status:result.status,comparisons:result.validation.comparisons,samples:result.samples.length,seconds:result.elapsed_seconds}));
