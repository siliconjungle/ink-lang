#!/usr/bin/env python3
"""Audit a registered resident experiment and report every evaluation loss.

This tool reads completed observations only. It does not fit, select or repair
profiles from evaluation data. Session and full engine lifetime remain separate.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import statistics

REGIMES = ('warm', 'cold', 'cpu-warm', 'gpu-warm')
BACKENDS = ('cpu', 'gpu', 'auto', 'profile')
METRICS = {
    'session': 'samples_ns',
    'complete_engine_lifetime': 'complete_lifecycle_samples_ns',
    'engine_initialization': 'engine_initialization_samples_ns',
    'preparation': 'preparation_samples_ns',
    'engine_close': 'engine_close_samples_ns',
}


def read(path):
    return json.loads(path.read_text())


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def summary(values):
    return dict(median=statistics.median(values), minimum=min(values),
                maximum=max(values), process_values=values)


def samples(row, metric, backend, fresh):
    values = row[METRICS[metric]][backend]
    if not isinstance(values, list) or not values:
        raise ValueError('missing timing samples')
    if metric != 'session' and not fresh:
        if any(v is not None for v in values):
            raise ValueError('reused engines cannot claim per-call lifetime costs')
        return None
    if any(type(v) not in (int, float) or not math.isfinite(v) or v < 0 for v in values):
        raise ValueError('invalid timing sample')
    if metric in ('session', 'complete_engine_lifetime') and any(v <= 0 for v in values):
        raise ValueError('nonpositive complete timing')
    return statistics.median(values)


def analyse(directory):
    directory = Path(directory)
    registration = read(directory / 'registration.json')
    completion = read(directory / 'complete.json')
    if completion.get('complete') is not True:
        raise ValueError('experiment is incomplete')
    # Filenames are generated by the harness, never paths supplied for reading.
    files = completion['files']
    for name, expected in files.items():
        if Path(name).name != name or not name.endswith('.json'):
            raise ValueError('invalid recorded filename')
        if digest(directory / name) != expected:
            raise ValueError('recorded bytes changed: ' + name)
    if 'registration.json' not in files or 'profile.json' not in files or 'fit-receipt.json' not in files:
        raise ValueError('missing registered profile provenance')
    protocol = registration['protocol']
    if protocol != read(directory / 'protocol.json'):
        raise ValueError('registered protocol differs')
    training, evaluation = protocol['training'], protocol['evaluation']
    if (set(training['sizes']) & set(evaluation['sizes']) or
            set(training['horizons']) & set(evaluation['horizons']) or
            training['seed'] == evaluation['seed']):
        raise ValueError('evaluation inputs overlap training')
    if digest(directory / 'ink') != completion['compiler_sha256']:
        raise ValueError('registered compiler bytes changed')
    profile = read(directory / 'profile.json')
    fit_receipt = read(directory / 'fit-receipt.json')
    fitted_files = fit_receipt['training_files']
    if len({Path(n).name for n in fitted_files}) != len(fitted_files):
        raise ValueError('ambiguous fitting inputs')
    fitted = {Path(n).name: h for n, h in fitted_files.items()}
    expected_train = {('' if regime == 'warm' else regime + '-') + f'train-{i}.json'
                      for regime in REGIMES for i in range(registration['training_processes_per_regime'])}
    if set(fitted) != expected_train or any(files.get(n) != h for n, h in fitted.items()):
        raise ValueError('profile fitting did not use exactly the registered training files')
    if registration['training_processes_per_regime'] < 3 or registration['evaluation_processes_per_regime'] < 3:
        raise ValueError('fresh process replication missing')
    provenance = None
    loaded = {}
    for regime in REGIMES:
        prefix = '' if regime == 'warm' else regime + '-'
        for split, count in [('train', registration['training_processes_per_regime']),
                             ('evaluation', registration['evaluation_processes_per_regime'])]:
            expected_mode = prefix + ('train' if split == 'train' else 'test')
            spec = training if split == 'train' else evaluation
            expected_keys = {(kernel, n, horizon) for kernel in ('ecs', 'physics')
                             for n in spec['sizes'] for horizon in spec['horizons']}
            records = []
            for i in range(count):
                name = f'{prefix}{split}-{i}.json'
                if name not in files:
                    raise ValueError('unrecorded observation: ' + name)
                record = read(directory / name)
                if record['mode'] != expected_mode or record['protocol'] != protocol:
                    raise ValueError('observation protocol mismatch')
                current = (record['source_hashes'], record['targetKey'], record['device'], record['environment'])
                if provenance is None:
                    provenance = current
                if current != provenance or profile['target_key'] != record['targetKey']:
                    raise ValueError('mixed binary or target provenance')
                if record['device'].get('isFallbackAdapter') is True:
                    raise ValueError('software adapter is not actual device evidence')
                rows = {(r['kernel'], r['n'], r['iterations']): r for r in record['receipts']}
                if set(rows) != expected_keys or len(rows) != len(record['receipts']):
                    raise ValueError('missing or duplicated evaluation cases')
                for row in rows.values():
                    if row.get('validated') is not True or any(row['backends'][b] != b for b in ('cpu', 'gpu')):
                        raise ValueError('unvalidated or fallback observation')
                    if split == 'evaluation' and row['backends']['auto'] != 'cpu':
                        raise ValueError('unprofiled control did not retain CPU')
                    for backend in (('cpu', 'gpu') if split == 'train' else BACKENDS):
                        for metric in METRICS:
                            samples(row, metric, backend, regime != 'warm')
                records.append(rows)
            loaded[regime, split] = records
    result = dict(schema=1, registration=registration, source_hashes=provenance[0],
                  target_key=provenance[1], device=provenance[2], regimes={},
                  limitations=[
                      'Two existing kernels: ECS integration and particle Euler integration; physics is not Box2D or a full engine.',
                      'Models fit complete session cost only. Engine lifetime is evaluated separately; it is not silently substituted into a session profile.',
                      'Fresh engine lifetime includes creation, requested prewarming, complete session and close. Browser startup and common module import are excluded; shared caches may already be warm.',
                      'Reused warm engines have no per-call whole-engine lifetime measurement.',
                      'Median of per-process medians; min/max are process variation, not confidence intervals. All evaluation cases and regressions are retained.',
                      'CPU memory is not measured; GPU arena counters are not total process memory. No memory-profitability claim.',
                      'Evaluation data never fits or repairs the profile. These inputs are new, but the two source kernels were already used during development.',
                  ])
    for name, expected in provenance[0].items():
        if Path(name).is_absolute() or '..' in Path(name).parts or '\\' in name:
            raise ValueError('invalid archived source path')
        if name == 'protocol':
            path = directory / 'protocol.json'
        elif name.startswith('build/resident-profile/'):
            path = directory / 'resident-bundle' / name.removeprefix('build/resident-profile/')
        elif name in registration['source_hashes']:
            if expected != registration['source_hashes'][name]:
                raise ValueError('registered measurement source changed')
            path = directory / 'sources' / name
        else:
            raise ValueError('unbound measurement source: ' + name)
        if digest(path) != expected:
            raise ValueError('archived measurement source changed: ' + name)
    for regime in REGIMES:
        records = loaded[regime, 'evaluation']
        rows = []
        for key in sorted(records[0]):
            cases = [r[key] for r in records]
            if len({(c['scope'], c['core_sha256'], json.dumps(c['features'], sort_keys=True)) for c in cases}) != 1:
                raise ValueError('per-process compiled context differs')
            metrics = {}
            for metric in METRICS:
                if metric != 'session' and regime == 'warm':
                    metrics[metric] = None
                    continue
                costs = {b: [samples(c, metric, b, regime != 'warm') for c in cases] for b in BACKENDS}
                entry = dict(costs_ns={b: summary(v) for b, v in costs.items()})
                if metric in ('session', 'complete_engine_lifetime'):
                    entry['speedup_over_unprofiled_auto'] = {
                        b: summary([a/v for a, v in zip(costs['auto'], costs[b])])
                        for b in ('cpu', 'gpu', 'profile')}
                    entry['profile_over_best_explicit_cost'] = summary([
                        p/min(c, g) for p, c, g in zip(costs['profile'], costs['cpu'], costs['gpu'])])
                metrics[metric] = entry
            rows.append(dict(kernel=key[0], n=key[1], iterations=key[2],
                             profile_backends=sorted({c['backends']['profile'] for c in cases}),
                             scope=cases[0]['scope'], metrics=metrics))
        result['regimes'][regime] = dict(rows=rows, regressions={
            metric: sum(r['metrics'][metric]['speedup_over_unprofiled_auto']['profile']['median'] < 1 for r in rows)
            for metric in ('session', 'complete_engine_lifetime') if rows[0]['metrics'][metric] is not None})
    return result



def render(report):
    lines = ['RESIDENT CPU / WEBGPU — SESSION AND ENGINE LIFETIME',
             'Speedup >1 means faster than unprofiled automatic CPU; <1 means slower.',
             'Ratios are medians of within-process comparisons across fresh browsers.', '']
    for regime, group in report['regimes'].items():
        lines += [regime, 'kernel    elements iterations profile backend   session speedup   full lifetime speedup']
        for row in group['rows']:
            session = row['metrics']['session']['speedup_over_unprofiled_auto']['profile']['median']
            lifetime = row['metrics']['complete_engine_lifetime']
            total = f"{lifetime['speedup_over_unprofiled_auto']['profile']['median']:.3f}x" if lifetime else 'not measured'
            lines.append(f"{row['kernel']:8} {row['n']:9} {row['iterations']:10} {','.join(row['profile_backends']):17} {session:12.3f}x {total:>23}")
        lines += ['Regressions: ' + json.dumps(group['regressions'], sort_keys=True), '']
    return '\n'.join(lines + report['limitations']) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('-o', '--output', required=True, type=Path)
    args = parser.parse_args()
    report = analyse(args.directory)
    args.output.write_text(json.dumps(report, indent=2) + '\n')
    args.output.with_suffix('.txt').write_text(render(report))
    print(json.dumps({regime: result['regressions'] for regime, result in report['regimes'].items()}))


if __name__ == '__main__':
    main()
